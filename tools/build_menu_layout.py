"""Validate and compile the authored menu layout without rebuilding art."""
import argparse
import json
import math
import os
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'content/ui/menu-layout.json'
CONTRACT = ROOT / 'content/ui/menu-layout-contract.json'


def validate_layout(payload):
    """Return a canonical independent clone, or reject with a field-path diagnostic."""
    contract = json.loads(CONTRACT.read_text(encoding='utf-8'))

    def fail(path, reason):
        raise ValueError(f'Invalid menu layout at {path}: {reason}')

    def exact_keys(value, keys, path):
        if not isinstance(value, dict):
            fail(path, 'expected object')
        for key in value:
            if key not in keys:
                fail(f'{path}.{key}' if path else key, 'unknown field')
        for key in keys:
            if key not in value:
                fail(f'{path}.{key}' if path else key, 'missing field')

    def finite(value, path):
        if type(value) not in (int, float) or (isinstance(value, float) and not math.isfinite(value)):
            fail(path, 'expected finite number')

    exact_keys(payload, ['schemaVersion', 'stage', 'regions'], '')
    finite(payload['schemaVersion'], 'schemaVersion')
    if payload['schemaVersion'] != contract['schemaVersion']:
        fail('schemaVersion', 'unsupported version')
    exact_keys(payload['stage'], ['width', 'height'], 'stage')
    for field, expected in contract['stage'].items():
        value = payload['stage'][field]
        finite(value, f'stage.{field}')
        if value != expected:
            fail(f'stage.{field}', 'fixed stage mismatch')
    exact_keys(payload['regions'], [region['id'] for region in contract['regions']], 'regions')
    regions = {}
    for region in contract['regions']:
        region_id = region['id']
        path = f'regions.{region_id}'
        values = payload['regions'][region_id]
        exact_keys(values, region['fields'], path)
        regions[region_id] = {}
        for field, descriptor in region['fields'].items():
            value = values[field]
            field_path = f'{path}.{field}'
            finite(value, field_path)
            if not descriptor['min'] <= value <= descriptor['max']:
                fail(field_path, 'outside allowed range')
            regions[region_id][field] = value
    return {'schemaVersion': contract['schemaVersion'], 'stage': dict(contract['stage']), 'regions': regions}


def render_outputs(payload):
    """Render validated modules without IO; paths are repository-relative strings."""
    layout = validate_layout(payload)
    contract = json.loads(CONTRACT.read_text(encoding='utf-8'))
    encode = lambda value: json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False)
    header = '// Generated by tools/build_menu_layout.py; edit the source JSON, then rebuild.\n'
    return {
        'content/ui/menu-layout-data.js': header + 'export const menuLayout = ' + encode(layout) + ';\n',
        'content/ui/menu-layout-regions.js': header + 'export const menuLayoutContract = ' + encode(contract)
        + ';\nexport const menuLayoutRegions = menuLayoutContract.regions;\n',
    }


def generated_outputs(payload):
    return {ROOT / path: content.encode('utf-8') for path, content in render_outputs(payload).items()}


def write_outputs(outputs):
    """Stage the complete pair before replacement; restore originals on IO failure."""
    originals = {path: path.read_bytes() if path.exists() else None for path in outputs}
    staged = {}
    replaced = []
    try:
        for path, content in outputs.items():
            staged[path] = _stage_output(path, content)
        for path, temporary in staged.items():
            os.replace(temporary, path)
            replaced.append(path)
    except BaseException:
        for path in reversed(replaced):
            if originals[path] is None:
                path.unlink(missing_ok=True)
            else:
                temporary = _stage_output(path, originals[path])
                try:
                    os.replace(temporary, path)
                finally:
                    temporary.unlink(missing_ok=True)
        raise
    finally:
        for temporary in staged.values():
            temporary.unlink(missing_ok=True)


def stale_outputs(outputs):
    return [path for path, content in outputs.items()
            if not path.exists() or path.read_bytes().replace(b'\r\n', b'\n') != content]


def _stage_output(path, content):
    descriptor, temporary_name = tempfile.mkstemp(prefix='.' + path.name + '.', suffix='.tmp', dir=path.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, 'wb') as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
    except BaseException:
        temporary.unlink(missing_ok=True)
        raise
    return temporary


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--build', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        payload = json.loads(SOURCE.read_text(encoding='utf-8'))
        outputs = generated_outputs(payload)
        if args.build:
            write_outputs(outputs)
        else:
            stale = stale_outputs(outputs)
            if stale:
                raise ValueError('Stale menu layout output: ' + ', '.join(str(path.relative_to(ROOT)) for path in stale))
    except (OSError, ValueError) as error:
        parser.exit(1, str(error) + '\n')
    print('Menu layout ' + ('built' if args.build else 'checked') + ': schema v1; 1672x941; both generated modules current.')


if __name__ == '__main__':
    main()
