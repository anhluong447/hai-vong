"""Compile opt-in HUD/dialogue presentation offsets; native geometry stays in existing CSS."""
import argparse
import json
import math
from pathlib import Path
try:
    from tools.build_menu_layout import write_outputs, stale_outputs
except ModuleNotFoundError:
    from build_menu_layout import write_outputs, stale_outputs

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'content/ui/screen-layout.json'
CONTRACT = ROOT / 'content/ui/screen-layout-contract.json'


def validate_screen_layout(payload):
    contract = json.loads(CONTRACT.read_text(encoding='utf-8'))

    def fail(path):
        raise ValueError('Invalid screen layout at ' + path)

    def keys(value, expected, path):
        if not isinstance(value, dict):
            fail(path)
        for key in set(value) ^ set(expected):
            fail(path + '.' + key)

    def number(value, path):
        if type(value) not in (int, float) or (isinstance(value, float) and not math.isfinite(value)):
            fail(path)

    keys(payload, ['schemaVersion', 'stage', 'regions'], 'layout')
    number(payload['schemaVersion'], 'schemaVersion')
    if payload['schemaVersion'] != 1:
        fail('schemaVersion')
    keys(payload['stage'], ['width', 'height'], 'stage')
    for key, value in contract['stage'].items():
        number(payload['stage'][key], 'stage.' + key)
        if payload['stage'][key] != value:
            fail('stage.' + key)
    keys(payload['regions'], [region['id'] for region in contract['regions']], 'regions')
    result = {'schemaVersion': 1, 'stage': dict(contract['stage']), 'regions': {}}
    for region in contract['regions']:
        rid = region['id']
        values = payload['regions'][rid]
        keys(values, region['fields'], 'regions.' + rid)
        result['regions'][rid] = {}
        for field, descriptor in region['fields'].items():
            value = values[field]
            path = 'regions.' + rid + '.' + field
            number(value, path)
            if not descriptor['min'] <= value <= descriptor['max']:
                fail(path)
            result['regions'][rid][field] = value
    return result


def render_outputs(payload):
    layout = validate_screen_layout(payload)
    contract = json.loads(CONTRACT.read_text(encoding='utf-8'))
    header = '// Generated by tools/build_screen_layout.py; edit screen-layout.json and rebuild.\n'
    encode = lambda data: json.dumps(data, indent=2, ensure_ascii=False, allow_nan=False)
    return {
        'content/ui/screen-layout-data.js': header + 'export const screenLayout = ' + encode(layout) + ';\n',
        'content/ui/screen-layout-regions.js': header + 'export const screenLayoutContract = ' + encode(contract)
        + ';\nexport const screenLayoutRegions = screenLayoutContract.regions;\n',
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument('--build', action='store_true')
    modes.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        outputs = {ROOT / path: text.encode('utf-8') for path, text in render_outputs(json.loads(SOURCE.read_text(encoding='utf-8'))).items()}
        if args.build:
            write_outputs(outputs)
        elif stale_outputs(outputs):
            raise ValueError('Stale screen layout modules; run tools/build_screen_layout.py --build')
    except (OSError, ValueError) as error:
        parser.exit(1, str(error) + '\n')
    print('Screen layout ' + ('built' if args.build else 'checked') + ': HUD/dialogue offsets; native geometry preserved.')


if __name__ == '__main__':
    main()
