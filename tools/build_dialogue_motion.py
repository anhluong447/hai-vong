"""Validate and compile data-authored Stage 4 UI motion; never rebuild art."""
import argparse
import hashlib
import json
import math
from pathlib import Path

ROOT=Path(__file__).resolve().parent.parent
SOURCE=ROOT/'content/ui/coastal-dialogue-motion.json'
OUTPUT=ROOT/'content/ui/coastal-dialogue-motion-data.js'


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    group=parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--build',action='store_true')
    group.add_argument('--check',action='store_true')
    args=parser.parse_args()
    data=json.loads(SOURCE.read_text(encoding='utf-8'))
    if data['version']!=1 or data['stage']!=[1672,941]:raise ValueError('Invalid motion plane')
    loop=data['clock']['loopMs']
    for name in ('wave','flowers','notebook','sheen'):
        period=data[name]['periodMs']
        if period<=0 or loop%period:raise ValueError('Non-seamless period: '+name)
    for name in ('flowers','notebook'):
        if not 0<=data[name]['degrees']<=1 or not 0<=data[name]['lift']<=3:raise ValueError('Excessive UI sway')
    if not 0<data['transition']['enterMs']<=1000 or not 0<data['transition']['exitMs']<=500:raise ValueError('Invalid transition')
    if not 0<=data['sheen']['opacity']<=0.15:raise ValueError('Reading-area sheen too strong')
    def finite(item):
        if isinstance(item,dict):return all(finite(value) for value in item.values())
        if isinstance(item,list):return all(finite(value) for value in item)
        return not isinstance(item,(int,float)) or math.isfinite(item)
    if not finite(data):raise ValueError('Non-finite motion parameter')
    for segment in data['wave']['commands']:
        if segment['command'] not in ('M','C') or len(segment['points'])!={'M':1,'C':3}[segment['command']]:raise ValueError('Invalid wave contour')
    manifest=json.loads((ROOT/data['artManifest']).read_text(encoding='utf-8'))
    known={asset['id'] for asset in manifest['assets']}
    if set(data['rasterCache'])-known:raise ValueError('Unknown native cache material')
    for asset in manifest['assets']:
        if hashlib.sha256((ROOT/asset['file']).read_bytes()).hexdigest().upper()!=asset['sha256']:raise ValueError('Art changed: '+asset['id'])
    content=('// Generated by tools/build_dialogue_motion.py; edit coastal-dialogue-motion.json.\nexport default '+json.dumps(data,ensure_ascii=False,indent=2)+';\n').encode('utf-8')
    if args.build:OUTPUT.write_bytes(content)
    elif not OUTPUT.exists() or OUTPUT.read_bytes().replace(b'\r\n',b'\n')!=content:raise ValueError('Stale motion output')
    print('Stage 4 '+('built' if args.build else 'checked')+': authored UI motion; seamless periods; v3 art hashes unchanged.')


if __name__=='__main__':main()
