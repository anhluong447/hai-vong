"""Build Stage 3 UI art; retain Stage 2 sources and native PNG bytes."""
import argparse
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
from build_replica_assets import dump, materials, sha, svg

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT/'assets/ui/coastal-replica/v3'
SOURCE = ROOT/'content/ui/coastal-dialogue-ui.json'


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--build', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    scene, config = read(SOURCE), read(PACK/'masters/materials.json')
    previous = read(ROOT/'assets/ui/coastal-replica/v2/manifest.json')
    vectors = materials(config)
    for name in ('harbor-print','foreground-note'):
        vectors.pop(name)
    vectors['dialogue-wave'] = vectors['dialogue-wave'].replace('opacity=".68"',f'opacity="{config["foamOpacity"]}"')
    for name, definition in config['overrides'].items():
        vectors[name] = svg(definition['size'],definition['body'],definition.get('defs',''))
    outputs = {ROOT/'content/ui/coastal-dialogue-ui-data.js':
        ('// Generated by tools/build_dialogue_ui.py; edit coastal-dialogue-ui.json.\nexport default '+dump(scene).rstrip()+';\n').encode('utf-8')}
    catalog_source = (ROOT/'content/locales/vi.js').read_text(encoding='utf-8')
    catalog = json.loads(catalog_source.split('export default ',1)[1].rstrip().removesuffix(';'))
    keys = [item['key'] for item in scene['text']+scene['environmentText']]
    keys += [item['textKey'] for item in scene['choices']+scene['views']]
    if set(keys)-catalog.keys():
        raise ValueError('Missing Stage 3 catalog keys: '+str(set(keys)-catalog.keys()))
    entries = []
    for name, content in vectors.items():
        tree = ET.fromstring(content)
        if any(node.tag.endswith('text') for node in tree.iter()):
            raise ValueError('Baked UI lettering: '+name)
        size = [int(tree.attrib['width']),int(tree.attrib['height'])]
        data = content.encode('utf-8')
        for folder in ('masters','exports'):
            outputs[PACK/folder/(name+'.svg')] = data
        entries.append({'id':'material.'+name,'file':f'assets/ui/coastal-replica/v3/exports/{name}.svg',
            'master':f'assets/ui/coastal-replica/v3/masters/{name}.svg','source':'assets/ui/coastal-replica/v3/masters/materials.json',
            'size':size,'alpha':True,'visibleBounds':[0,0,*size],'sha256':sha(data)})
    for asset in previous['assets']:
        if asset['id'] not in ('dialogue.harbor-print','dialogue.foreground-left','dialogue.foreground-right'):
            continue
        data = (ROOT/asset['master']).read_bytes()
        if sha(data)!=asset['sha256']:
            raise ValueError('Inherited PNG changed: '+asset['id'])
        name = Path(asset['file']).name
        for folder in ('masters','exports'):
            outputs[PACK/folder/name] = data
        entries.append({**{key:asset[key] for key in ('id','size','alpha','visibleBounds','sha256')},
            'file':f'assets/ui/coastal-replica/v3/exports/{name}',
            'master':f'assets/ui/coastal-replica/v3/masters/{name}',
            'source':asset['master'],'provenance':'Stage 2 imagegen prompts retained; native PNG bytes inherited'})
    known={asset['id'] for asset in entries}
    for art in scene['art']:
        if art['asset'] not in known or art['layer'] not in scene['layerOrder']:
            raise ValueError('Unknown UI placement: '+art['id'])
        x,y,w,h=art['bounds']
        if min(x,y)<0 or min(w,h)<=0 or x+w>1672 or y+h>941:
            raise ValueError('UI placement outside stage: '+art['id'])
    for profile in scene['lighting']['shadows'].values():
        if not 0<=profile['opacity']<=1 or not 0<=profile['blur']<=12:
            raise ValueError('Invalid local shadow')
    for font in previous['fonts']:
        for item in font.get('sources',[]):
            if sha((ROOT/item['file']).read_bytes())!=item['sha256']:
                raise ValueError('Inherited font changed')
    font_pack=read(ROOT/'assets/fonts/coastal-replica/manifest.json')
    for font in font_pack['fonts']:
        for item in font['files']:
            if sha((ROOT/item['path']).read_bytes())!=item['sha256']:
                raise ValueError('Pinned font changed')
    mask_path='assets/ui/coastal-replica/v3/review/ui-mask.svg'
    body=''.join(f'<path d="{region["path"]}" fill="white"/>' for region in config['comparison']['regions'])
    mask=svg([1672,941],body).encode('utf-8')
    outputs[ROOT/mask_path]=mask
    context=next(asset for asset in previous['assets'] if asset['id']=='dialogue.newsroom')
    if sha((ROOT/context['file']).read_bytes())!=context['sha256']:
        raise ValueError('Preview context changed')
    context={**{key:context[key] for key in ('file','size','visibleBounds','sha256')},'id':'context.newsroom','scope':'replaceable-context'}
    for entry in entries:
        entry.update({'version':3,'scope':'ui','pivot':[0,0],
            'textPolicy':'live locale copy; no baked lettering',
            'instances':[item for item in scene['art'] if item['asset']==entry['id']]})
    manifest={'version':3,'pack':'coastal-dialogue-ui-stage3','stage':[1672,941],'scopeRevision':2,
        'assets':entries,'contextAssets':[context],'paperContour':config['paper']['path'],'paperEdge':config['paper']['edge'],
        'fonts':font_pack['fonts'],'fontManifest':'assets/fonts/coastal-replica/manifest.json',
        'compositionSource':'content/ui/coastal-dialogue-ui.json',
        'compositionSourceSHA256':sha(SOURCE.read_text(encoding='utf-8').encode('utf-8')),
        'sourceReference':config['reference'],'sourceReferenceSHA256':sha((ROOT/config['reference']).read_bytes()),
        'comparisonMask':{'file':mask_path,'sha256':sha(mask),**config['comparison']},
        'textKeys':keys,'lighting':scene['lighting'],
        'gate':'R15/R16 implementation; R17 scoped review, not automatic G2 certification'}
    outputs[PACK/'manifest.json']=dump(manifest).encode('utf-8')
    for path,data in outputs.items():
        if args.build:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
        else:
            actual=path.read_bytes() if path.exists() else None
            if actual is not None and path.suffix!='.png':actual=actual.replace(b'\r\n',b'\n')
            if actual!=data:raise ValueError('Stale Stage 3 output: '+str(path.relative_to(ROOT)))
    print(f'Stage 3 {"built" if args.build else "checked"}: {len(entries)} UI assets; separate context; local lighting and native review mask.')


if __name__=='__main__':
    main()
