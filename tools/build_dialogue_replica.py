"""Build Stage 2 sources, independent exports and a provenance manifest.

SVG art is code-native. PNG files are inspected and copied byte-for-byte only.
Stage 1 sources and exports are retained without modification.
"""
import argparse
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
from PIL import Image
from build_replica_assets import materials, svg, glyphs, sha, dump

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT / 'assets/ui/coastal-replica/v2'
SOURCE = ROOT / 'content/ui/coastal-dialogue.json'


def read(path):
    return json.loads(path.read_text(encoding='utf-8'))


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument('--build', action='store_true')
    group.add_argument('--check', action='store_true')
    args = parser.parse_args()
    config, scene = read(PACK/'masters/materials.json'), read(SOURCE)
    prompts = read(PACK/'prompts.json')
    vectors = materials(config)
    for name in ('harbor-print','foreground-note'):
        vectors.pop(name)
    vectors['dialogue-wave'] = vectors['dialogue-wave'].replace('opacity=".68"','opacity=".19"')
    for name, definition in config['overrides'].items():
        vectors[name] = svg(definition['size'],definition['body'],definition.get('defs',''))
    required = set(range(0x1ea0,0x1efa)) | {0x102,0x103,0x110,0x111,0x128,0x129,0x168,0x169,0x1a0,0x1a1,0x1af,0x1b0,0x300,0x301,0x303,0x309,0x323}
    fonts = read(ROOT/'assets/fonts/coastal-replica/manifest.json')
    font_checks = []
    for font in fonts['fonts']:
        for item in font['files']:
            if sha((ROOT/item['path']).read_bytes()) != item['sha256']:
                raise ValueError('Font/source hash differs: '+item['path'])
        missing = sorted(required-glyphs(ROOT/font['files'][0]['path']))
        if missing:
            raise ValueError('Missing Vietnamese glyphs: '+font['family'])
        font_checks.append({'family':font['family'],'vietnameseCodepointsChecked':len(required),'missing':missing})
    outputs = {ROOT/'content/ui/coastal-dialogue-data.js':
        ('// Generated by tools/build_dialogue_replica.py; edit coastal-dialogue.json.\nexport default '+dump(scene).rstrip()+';\n').encode('utf-8')}
    inherited_paths=[ROOT/'assets/fonts'/f'be-vietnam-pro-{index}.ttf' for index in range(5)]
    coverage=set().union(*(glyphs(path) for path in inherited_paths))
    if required-coverage:
        raise ValueError('Inherited Be Vietnam Pro subsets lack Vietnamese coverage')
    font_checks.append({'family':'Be Vietnam Pro','vietnameseCodepointsChecked':len(required),'missing':[],
        'provenance':'existing project OFL font pack; retained from commit 1519393',
        'sources':[{'file':path.relative_to(ROOT).as_posix(),'sha256':sha(path.read_bytes())} for path in inherited_paths],
        'license':{'file':'assets/fonts/OFL.txt','hashInput':'UTF-8 LF',
            'sha256':sha((ROOT/'assets/fonts/OFL.txt').read_text(encoding='utf-8').encode('utf-8'))}})
    entries = []
    text_keys = [item['key'] for item in scene['text']+scene['environmentText']]
    text_keys += [item['textKey'] for item in scene['choices']]
    if len(text_keys) != len(set(text_keys)):
        raise ValueError('Repeated authored text key')
    instances = list(scene['art'])
    for asset,layer in [('material.dialogue-wave','wave'),('material.dialogue-paper','paper')]:
        instances.append({'id':layer+'-plane','asset':asset,'layer':layer,'bounds':scene['paperBounds']})
    for choice in scene['choices']:
        for variant in ('gold','plain'):
            instances.append({'id':choice['id']+'-'+variant,'asset':'material.choice-'+variant,
                'layer':'print','bounds':choice['bounds'],'textKeys':[choice['textKey']],
                'variant':'selected' if variant=='gold' else 'unselected'})
        x,y,_,_=choice['bounds']
        instances.append({'id':choice['id']+'-icon','asset':'material.icons','layer':'print',
            'bounds':[x+29,y+16,28,28],'symbol':choice['icon'],'textKeys':[choice['textKey']]})
    instances.append({'id':'continue-icon','asset':'material.icons','layer':'text','bounds':scene['returnIcon']})
    for asset,bounds,role in [('material.newspaper-rules',scene['newspaper']['rules'],'newspaper-rules'),
                              ('dialogue.harbor-print',scene['newspaper']['illustration'],'newspaper-illustration')]:
        instances.append({'id':role,'asset':asset,'layer':'portraits','bounds':bounds,
            'transform':scene['newspaper']['transform'],'coordinateSpace':'newspaper-local',
            'textKeys':['ui.replica.dialogue.newspaper.1']})
    if len({item['id'] for item in instances}) != len(instances):
        raise ValueError('Repeated art instance ID')
    for item in instances:
        x,y,w,h = item['bounds']
        if min(x,y)<0 or min(w,h)<=0 or x+w>1672.001 or y+h>941.001:
            raise ValueError('Art leaves native stage: '+item['id'])
        if item.get('clip') and item['clip'] not in scene['clips']:
            raise ValueError('Unknown art mask: '+item['id'])
    def add(asset_id, name, data, size, alpha, bounds, provenance):
        master, export = PACK/'masters'/name, PACK/'exports'/name
        outputs[export] = data
        uses = [{**item,'z':scene['layerOrder'].index(item['layer'])*10,
                 'placementPivot':item['bounds'][:2]} for item in instances if item['asset']==asset_id]
        entries.append({'id':asset_id,'version':2,'master':master.relative_to(ROOT).as_posix(),
            'file':export.relative_to(ROOT).as_posix(),'size':size,'alpha':alpha,'visibleBounds':bounds,
            'sha256':sha(data),'source':provenance,'instances':uses,
            'crop':'PNG native bytes retained; portraits use uniform registration; print/material rectangles are authored separately',
            'pivot':[0,0],'pivotRole':'file origin; placement/face anchors are distinct from future motion pivots',
            'rights':'project art/vector source; prompts retained; fonts have separate OFL licenses',
            'textPolicy':'all readable lettering is live catalog content',
            'status':'Stage 2 static review; gate status in review report'})
    for name, content in vectors.items():
        if any(node.tag.endswith('text') for node in ET.fromstring(content).iter()):
            raise ValueError('Lettering baked into SVG: '+name)
        parsed=ET.fromstring(content)
        size=[int(parsed.attrib['width']),int(parsed.attrib['height'])]
        data=content.encode('utf-8')
        outputs[PACK/'masters'/(name+'.svg')]=data
        add('material.'+name,name+'.svg',data,size,True,[0,0,*size],
            'assets/ui/coastal-replica/v2/masters/materials.json')
    for item in prompts['outputs']:
        path=PACK/item['file']
        with Image.open(path) as image:
            size=list(image.size)
            alpha=image.getchannel('A') if image.mode=='RGBA' else None
            bbox=alpha.getbbox() if alpha else (0,0,*size)
            if bbox is None:
                raise ValueError('Empty generated asset: '+item['id'])
            x,y,right,bottom=bbox
            bounds=[x,y,right-x,bottom-y]
        add(item['id'],path.name,path.read_bytes(),size,alpha is not None,bounds,
            'assets/ui/coastal-replica/v2/prompts.json')
    known={entry['id'] for entry in entries}
    if any(item['asset'] not in known for item in instances):
        raise ValueError('Composition uses an unknown asset')
    manifest={'version':2,'pack':'coastal-dialogue-stage2','stage':[1672,941],
        'sourceReference':config['reference'],'sourceReferenceSHA256':sha((ROOT/config['reference']).read_bytes()),
        'compositionSource':'content/ui/coastal-dialogue.json',
        'compositionSourceSHA256':sha(SOURCE.read_text(encoding='utf-8').encode('utf-8')),
        'assets':entries,'fonts':font_checks,'fontManifest':'assets/fonts/coastal-replica/manifest.json',
        'textKeys':text_keys,'registration':scene['registration'],
        'paperContour':config['paper']['path'],
        'gate':'native comparison and alpha review required; no parity inferred from tests'}
    outputs[PACK/'manifest.json']=dump(manifest).encode('utf-8')
    for path,data in outputs.items():
        if args.build:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
        else:
            actual=path.read_bytes() if path.is_file() else None
            if actual is not None and path.suffix!='.png':
                actual=actual.replace(b'\r\n',b'\n')
            if actual!=data:
                raise ValueError('Stale Stage 2 output: '+path.relative_to(ROOT).as_posix())
    print(f'Stage 2 {"built" if args.build else "checked"}: {len(entries)} assets; {len(instances)} independent instances; native PNG bytes and local font hashes preserved.')


if __name__=='__main__':
    main()
